"""Writes the board's copies of the files it serves:

  ../src/clip/files.h      the helper (devkit_clip.py, clipcrypto.py) and its four installers
  ../src/clip/clip_page.h  the page (../page/clip.html) with the tested crypto (../tools/clipcrypto.js)

The files in helper/, page/ and tools/clipcrypto.js are the source. After changing any of them,
run:  python3 helper/embed.py
"""
import gzip
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
SRC = ROOT / "src" / "clip"
FILES = [("CLIP_PY", "devkit_clip.py"), ("CRYPTO_PY", "clipcrypto.py"), ("INSTALL_SH", "install.sh"),
         ("UNINSTALL_SH", "uninstall.sh"), ("INSTALL_PS1", "install.ps1"), ("UNINSTALL_PS1", "uninstall.ps1")]
DELIM = "~clip~"


def gz(name, data):
    """Bytes as a C array, gzipped with a fixed timestamp so the same source gives the same file."""
    z = gzip.compress(data, compresslevel=9, mtime=0)
    rows = ",".join("0x%02x" % b for b in z)
    return "static const uint8_t %s_GZ[] PROGMEM = {%s};\nstatic const size_t %s_GZ_LEN = %d;\n" % (name, rows, name, len(z))


def raw(name, text):
    assert ")" + DELIM + '"' not in text, name
    return 'static const char %s[] PROGMEM = R"%s(%s)%s";\n' % (name, DELIM, text, DELIM)


parts = ["#pragma once\n// GENERATED by helper/embed.py from the files in helper/. Edit those, not this.\n"]
for name, fn in FILES:
    text = (HERE / fn).read_text(encoding="utf-8")
    if fn.endswith(".ps1"):
        text = text.replace("\r\n", "\n").replace("\n", "\r\n")   # Windows line endings for PowerShell
    parts.append(raw(name, text))
    if fn.endswith(".py"):              # the board serves these gzipped; the installers unpack them
        parts.append(gz(name, text.encode("utf-8")))
(SRC / "files.h").write_text("\n".join(parts), encoding="utf-8")

js = (ROOT / "tools" / "clipcrypto.js").read_text(encoding="utf-8")
crypto = js[js.index("// CRYPTO-BEGIN"):js.index("// CRYPTO-END") + len("// CRYPTO-END")]
page = (ROOT / "page" / "clip.html").read_text(encoding="utf-8")
assert page.count("/*CRYPTO*/") == 1
page = page.replace("/*CRYPTO*/", crypto)
(SRC / "clip_page.h").write_text("#pragma once\n// GENERATED by helper/embed.py from page/clip.html and tools/clipcrypto.js. Edit those, not this.\n"
                                 + raw("CLIP_PAGE", page) + gz("CLIP_PAGE", page.encode("utf-8")), encoding="utf-8")
for f in ("files.h", "clip_page.h"):
    print("wrote %s (%d bytes)" % (f, (SRC / f).stat().st_size))
