"""Puts pets.js where it's drawn, and writes ../src/pet/files.h for the board to serve.

pets.js is the one drawing of the pets. It goes into two places, so the two can never differ:
  - the desktop helper (devkit_pet.py), which shows it in a transparent web view;
  - the phone page (src/pet/pet_page.h), which draws it on a canvas.
Then files.h is generated from the helper and its installers.

The files in this folder are the source. After changing any of them, run:  python3 helper/embed.py
"""
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
SRC = HERE.parent / "src" / "pet"
OUT = SRC / "files.h"
FILES = [("HELPER_PY", "devkit_pet.py"), ("INSTALL_SH", "install.sh"), ("UNINSTALL_SH", "uninstall.sh"),
         ("INSTALL_PS1", "install.ps1"), ("UNINSTALL_PS1", "uninstall.ps1")]
DELIM = "~pet~"

js = (HERE / "pets.js").read_text()
assert "'''" not in js and ")" + DELIM + '"' not in js and ")HTML\"" not in js

# 1. pets.js into the helper and the page (replacing the marker, or the copy put there last time)
py = HERE / "devkit_pet.py"
t, n = re.subn(r"^(#@PETS_JS@|PETS_JS = r'''.*?''')$", lambda _: "PETS_JS = r'''" + js + "'''", py.read_text(),
               count=1, flags=re.M | re.S)
assert n == 1, "no PETS_JS marker in devkit_pet.py"
py.write_text(t)
page = SRC / "pet_page.h"
t, n = re.subn(r"^(//@PETS_JS@|// pets\.js >>>.*?// <<< pets\.js)$", lambda _: "// pets.js >>>\n" + js + "\n// <<< pets.js",
               page.read_text(), count=1, flags=re.M | re.S)
assert n == 1, "no PETS_JS marker in pet_page.h"
page.write_text(t)

# 2. the helper and installers, for the board to serve
parts = ["#pragma once\n// GENERATED by helper/embed.py from the files in helper/ — edit those, not this.\n"]
for name, fn in FILES:
    text = (HERE / fn).read_text()
    if fn.endswith(".ps1"):
        text = text.replace("\r\n", "\n").replace("\n", "\r\n")   # Windows line endings for PowerShell
    assert ")" + DELIM + '"' not in text, fn
    parts.append('static const char %s[] PROGMEM = R"%s(%s)%s";\n' % (name, DELIM, text, DELIM))
OUT.write_text("\n".join(parts))
print("pets.js (%d bytes) -> helper + page; wrote %s" % (len(js), OUT.name))
